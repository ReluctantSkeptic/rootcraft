def add_defs(cards):
    """Attach def to each real card (in place). Raises if a real word has no def."""
    for c in cards:
        if c.get('real') and not c.get('def'):
            k = c['word'].lower()
            if k not in DEFS:
                raise KeyError(f'no def for real word {k!r} in work/art/word_defs.py')
            c['def'] = DEFS[k]
    return cards
